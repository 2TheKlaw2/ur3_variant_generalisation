#!/usr/bin/env python3
"""Replay a VALIDATED short V1 alignment joint plan on isolated fake hardware only.

The plan must come from align_to_grip_plan_only's CSV export, after full
collision-checked Cartesian planning and final TCP forward-kinematics check.
This script does not calculate paths and cannot control real/ scaled controllers.
"""
import argparse
import csv
import math
import time
from pathlib import Path

import rclpy
from rclpy.action import ActionClient
from rclpy.node import Node
from rclpy.qos import qos_profile_sensor_data
from sensor_msgs.msg import JointState
from control_msgs.action import FollowJointTrajectory
from action_msgs.msg import GoalStatus
from trajectory_msgs.msg import JointTrajectoryPoint
from builtin_interfaces.msg import Duration

from sim_fake_guard import await_result, verify_fake_only

JOINTS = ('shoulder_pan_joint','shoulder_lift_joint','elbow_joint',
          'wrist_1_joint','wrist_2_joint','wrist_3_joint')
DEFAULT_PLAN = Path('/tmp/v1_align_to_grip_joint_plan_001.csv')
ROOT = Path.home() / 'ros2_ws/src/ur3_variant_generalisation'
REFERENCE = ROOT / 'demonstrations/processed/v1_reach_full_joint_sim_candidate_001.csv'


def read_joint_csv(path):
    with path.open(newline='') as f:
        rd = csv.DictReader(f)
        if rd.fieldnames != ['time', *JOINTS]:
            raise RuntimeError(f'Unexpected joint CSV header: {rd.fieldnames}')
        rows = list(rd)
    if not rows:
        raise RuntimeError('Empty joint CSV: ' + str(path))
    times = [float(r['time']) for r in rows]
    joints = [[float(r[j]) for j in JOINTS] for r in rows]
    if any(not math.isfinite(x) for x in times + [v for row in joints for v in row]):
        raise RuntimeError('Nonfinite time or joint value')
    return times, joints


def check_plan(path):
    if path.resolve() != DEFAULT_PLAN:
        raise RuntimeError('Only the fixed, reviewed /tmp alignment plan is accepted')
    times, q = read_joint_csv(path)
    ref_t, ref_q = read_joint_csv(REFERENCE)
    del ref_t
    if not (5 <= len(q) <= 80):
        raise RuntimeError('Expected a SHORT alignment plan (5–80 points)')
    if not (0 <= times[0] < 0.15 and 0.1 < times[-1] <= 25.0):
        raise RuntimeError('Unexpected alignment duration')
    if any(b <= a for a, b in zip(times, times[1:])):
        raise RuntimeError('Waypoint times not strictly increasing')
    if max(abs(a-b) for a, b in zip(q[0], ref_q[-1])) > 0.02:
        raise RuntimeError('Alignment plan does not start at completed V1 reach')
    if max(abs(a-b) for a, b in zip(q[0], q[-1])) > 0.25:
        raise RuntimeError('Alignment displacement exceeds short-movement safety envelope')
    if max(abs(b-a) for qa, qb in zip(q, q[1:]) for a,b in zip(qa,qb)) >= 0.05:
        raise RuntimeError('Joint discontinuity in alignment plan')
    if any(abs(v) > 2*math.pi+0.1 for row in q for v in row):
        raise RuntimeError('Joint value outside broad numerical bounds')
    return times, q


class Monitor(Node):
    def __init__(self):
        super().__init__('v1_fake_alignment_only')
        self.joints = {}
        self.updated = 0.0
        self.recording = False
        self.begin = 0.0
        self.samples = []
        self.create_subscription(JointState, '/joint_states', self._cb, qos_profile_sensor_data)

    def _cb(self, msg):
        self.joints = dict(zip(msg.name, msg.position))
        self.updated = time.monotonic()
        if self.recording and all(name in self.joints for name in JOINTS):
            self.samples.append([self.updated-self.begin] + [self.joints[n] for n in JOINTS])

    def positions(self):
        self.updated = 0.0
        limit = time.monotonic() + 6.0
        while self.updated == 0.0 and time.monotonic() < limit:
            rclpy.spin_once(self, timeout_sec=0.1)
        if not self.updated or time.monotonic() - self.updated > 0.5:
            raise RuntimeError('Missing or stale /joint_states on fake domain')
        if not all(n in self.joints for n in JOINTS):
            raise RuntimeError('Missing arm joint in /joint_states')
        return [self.joints[n] for n in JOINTS]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--plan', type=Path, default=DEFAULT_PLAN)
    parser.add_argument('--slowdown', type=float, default=2.0)
    parser.add_argument('--log', type=Path, default=ROOT/'results/v1_align_sim_actual_001.csv')
    args = parser.parse_args()
    if not 1.0 <= args.slowdown <= 5.0:
        parser.error('Slowdown must be 1 to 5')
    if args.log.exists():
        parser.error('Log exists; refusing to overwrite: ' + str(args.log))

    times, poses = check_plan(args.plan)
    # A trajectory generated by MoveIt is retimed; slowdown makes it more conservative.
    scaled = [t*args.slowdown for t in times]
    for joint_idx, name in enumerate(JOINTS):
        speed = [(n[joint_idx]-p[joint_idx])/(tn-tp)
                 for p,n,tp,tn in zip(poses,poses[1:],scaled,scaled[1:])]
        if max(map(abs,speed)) > 0.3:
            raise RuntimeError('Velocity too high for fake alignment: '+name)
    print(f'FAKE ALIGN: {len(poses)} joint points, {scaled[-1]:.3f} s.')
    print('No pre-positioning, no return home, no real robot action.')

    rclpy.init()
    node = Monitor()
    handle = None
    try:
        verify_fake_only(node)
        actual = node.positions()
        error = max(abs(x-y) for x,y in zip(actual, poses[0]))
        print(f'Current fake start error: {error:.6f} rad')
        if error > 0.015:
            raise RuntimeError('Fake robot is not at the alignment plan start')

        action = ActionClient(node, FollowJointTrajectory,
                              '/joint_trajectory_controller/follow_joint_trajectory')
        if not action.wait_for_server(timeout_sec=7):
            raise RuntimeError('Fake joint trajectory action unavailable')
        print('This action WILL move only the virtual UR3e joint states.')
        if input('Type ALIGN to simulate alignment: ').strip() != 'ALIGN':
            raise RuntimeError('No confirmation; no movement')

        verify_fake_only(node)
        actual = node.positions()
        if max(abs(x-y) for x,y in zip(actual,poses[0])) > 0.015:
            raise RuntimeError('Start changed since confirmation; no movement')

        goal = FollowJointTrajectory.Goal()
        goal.trajectory.joint_names = list(JOINTS)
        for t, q in zip(scaled, poses):
            ns = round(t*1e9)
            pt = JointTrajectoryPoint()
            pt.positions = list(q)
            pt.time_from_start = Duration(sec=ns//1_000_000_000,
                                          nanosec=ns%1_000_000_000)
            goal.trajectory.points.append(pt)
        node.begin = time.monotonic()
        node.recording = True
        handle = await_result(node, action.send_goal_async(goal))
        if not handle.accepted:
            raise RuntimeError('Fake controller rejected alignment goal')
        result = await_result(node, handle.get_result_async(), max(15.0, 4*scaled[-1]+10))
        node.recording = False
        if result.status != GoalStatus.STATUS_SUCCEEDED or result.result.error_code != 0:
            raise RuntimeError('Fake alignment action failed: '+result.result.error_string)
        final = node.positions()
        e = max(abs(x-y) for x,y in zip(final,poses[-1]))
        print(f'FAKE ALIGNMENT ACTION SUCCESS. Max joint endpoint error: {e:.7f} rad')
        if e > 0.015:
            raise RuntimeError('Alignment execution endpoint discrepancy')
    except Exception as exc:
        print('FAKE ALIGNMENT STOPPED:', exc)
        if handle is not None and handle.accepted:
            try:
                await_result(node, handle.cancel_goal_async(), 3.0)
            except Exception:
                print('Cancellation unconfirmed; stop fake controller if needed')
        raise SystemExit(1)
    finally:
        node.recording = False
        if node.samples:
            args.log.parent.mkdir(parents=True, exist_ok=True)
            with args.log.open('x',newline='') as f:
                wr = csv.writer(f)
                wr.writerow(['elapsed_s', *JOINTS])
                wr.writerows(node.samples)
            print('Saved actual fake alignment states:', args.log)
        node.destroy_node()
        rclpy.shutdown()

if __name__ == '__main__':
    main()
